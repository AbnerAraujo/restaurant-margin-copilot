/**
 * A request for business ADVICE, as the composer emits it. Deliberately not a
 * bare question string like the computed path's output — advice is a
 * different action with a different destination, and collapsing it into "just
 * another question" is exactly the shape that would hide that.
 *
 * `question` is the grounding question: one of the 8 computed capabilities'
 * own questions, composed by the exact same `composeGuidedQuestion` and
 * therefore guaranteed answerable on identical terms. That two-stage shape is
 * forced by the backend, not chosen for convenience —
 * `httpapi.HandleBusinessInsight` refuses any advice request whose posted
 * `tool_calls` don't re-derive to the claimed kind (spec SC-005), and
 * `BusinessInsightChip` may only fetch advice on an explicit tap (spec
 * FR-014). So there is no "POST the kind and get advice" path to model: the
 * pattern must be computed first, and the owner must then choose to pay for
 * an interpretation of it.
 */
export interface GuidedAdviceRequest {
  insightKind: BusinessInsightKind
  question: string
}

/**
 * How many date ranges an advisory topic's grounding question needs. Only a
 * margin decline is defined relative to another period; every other insight
 * pattern is detected within a single one.
 */
export function advisoryPeriodCount(capability: AdvisoryCapability): 1 | 2 {
  return capability.groundedBy === 'margin_delta' ? 2 : 1
}

/**
 * Normalises the advisory form's draft into the exact draft its grounding
 * category expects. `list_discrepancies` is the only grounding category with a
 * sub-choice, and for advice the answer is never "one day": a discrepancy
 * PATTERN worth advising on is a recurrence, which only a period can show.
 */
function advisoryGroundingDraft(
  capability: AdvisoryCapability,
  draft: GuidedDraft,
): GuidedDraft {
  if (capability.groundedBy === 'discrepancies') {
    return { ...draft, scope: 'period' }
  }
  return draft
}

/**
 * Turns a filled-in advisory form into a `GuidedAdviceRequest`, or `null`
 * while it's incomplete or carries a date outside `bounds` — the same gate,
 * for the same reason, as `toGuidedParams`, and literally the same code path:
 * the grounding question is composed through `toGuidedParams` +
 * `composeGuidedQuestion`, so the advisory path cannot compose a question the
 * computed path wouldn't have.
 */
export function composeAdviceRequest(
  insightKind: BusinessInsightKind,
  draft: GuidedDraft,
  bounds?: DateBounds,
): GuidedAdviceRequest | null {
  const capability = findAdvisoryCapability(insightKind)
  if (!capability) return null
  const params = toGuidedParams(
    capability.groundedBy,
    advisoryGroundingDraft(capability, draft),
    bounds,
  )
  if (!params) return null
  return { insightKind, question: composeGuidedQuestion(params) }
}
