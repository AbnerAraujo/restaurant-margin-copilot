/**
 * THE authoritative frontend catalog of what this product can actually do.
 *
 * Why this file exists at all: "a hand-maintained list of capabilities" has
 * gone stale in this codebase twice — the Help page hardcoded "seven tools"
 * after an eighth shipped, and `Chat/exampleQuestions.ts` still has no entry
 * for that eighth tool. Both failures had the same root cause: several
 * independent lists, each of which a person had to remember to update. This
 * module is the one list. Every "what can I do here" surface reads from it
 * rather than restating it.
 *
 * Two things keep it honest, and neither is a person remembering:
 *
 *  1. **A contract test against the real Go code.** `capabilities.test.ts`
 *     parses `backend/internal/mcptools/*.go` for every `mcp.NewTool("…")`
 *     actually registered, and `backend/internal/advisor/advisor.go` for
 *     every insight `Kind…` constant, and asserts this file's two lists match
 *     them EXACTLY — in both directions. Ship a ninth MCP tool and the
 *     frontend test suite goes red naming the tool nobody surfaced. That is
 *     the mechanism the previous two lists lacked.
 *
 *  2. **Types the compiler enforces.** `McpToolName` and `BusinessInsightKind`
 *     are derived from the const tuples below, so a capability entry can only
 *     name a tool/kind this file already knows about.
 *
 * Deliberately NOT a codegen pipeline. The Go tool contracts are stable, the
 * plain-language labels are human copy that no generator could write, and a
 * generated-file build step is real ongoing cost for a fixed set of eight
 * tools. A test that fails loudly on drift buys the same guarantee for a
 * fraction of the machinery.
 *
 * Equally deliberately NOT generated by asking the model to describe its own
 * capabilities — the reason `exampleQuestions.ts`'s doc comment already
 * gives: a model listing what it can do is a fresh hallucination surface, and
 * offering a question the product cannot answer is the same class of lie as
 * inventing a number.
 *
 * Framework-free on purpose (no React, no imports): the composer, the Help
 * page, and any future consumer all read it, and its contract test parses Go
 * source in a plain Node context.
 */

