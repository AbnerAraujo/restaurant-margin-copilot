/**
 * One thing the product can ADVISE on: general business practice connected to
 * a real computed pattern, generated by one billed Claude Sonnet 5 call
 * (`POST /api/business-insight`, `backend/internal/advisor/`).
 *
 * This is a fundamentally different epistemic category from a
 * {@link ComputedCapability} and must be presented as one everywhere it
 * appears — probabilistic guidance, not a provenance-backed fact.
 *
 * `groundedBy` is the load-bearing field, and it encodes a real backend
 * constraint rather than a UI convenience. `HandleBusinessInsight` REFUSES any
 * advice request whose posted `tool_calls` don't re-derive to the claimed kind
 * (spec SC-005) — so advice cannot be requested out of thin air, and there is
 * no "just POST the kind" path to model. Every insight kind is reachable only
 * by first computing the pattern it is about, which is exactly what the named
 * computed capability's question does. Advice is therefore always a two-stage
 * action: compute the fact, then optionally pay for interpretation of it.
 *
 * `unavailableNote` is the honest copy for the outcome that is not an error:
 * the question was answered correctly and the pattern simply is not present.
 */
export interface AdvisoryCapability {
  nature: 'advisory'
  insightKind: BusinessInsightKind
  /** Sentence-case, verb-first button label. No terminal punctuation. */
  label: string
  /** One-line helper sentence shown under the label. */
  description: string
  /** The computed capability whose question surfaces this pattern. */
  groundedBy: ComputedCapabilityId
  /** Shown when the grounding answer came back clean — good news, not a failure. */
  unavailableNote: string
}

