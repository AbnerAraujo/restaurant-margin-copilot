/** Every capability this product has, computed and advisory alike. */
export const PRODUCT_CAPABILITIES: (ComputedCapability | AdvisoryCapability)[] = [
  ...COMPUTED_CAPABILITIES,
  ...ADVISORY_CAPABILITIES,
]

/** The advisory capability for `kind`, or `undefined` for an unknown kind. */
export function findAdvisoryCapability(
  kind: string,
): AdvisoryCapability | undefined {
  return ADVISORY_CAPABILITIES.find((c) => c.insightKind === kind)
}
